# ---------------------------------------------------------------- booking windows
# T is the travel date. T+N means the fare was observed N days BEFORE travel.
# (The PS writes these as T+1 ... T+45; Context-of-PS.md fixes the reading:
#  T+45 = booked 45 days ahead = typically cheapest.)
BOOKING_WINDOWS: tuple[int, ...] = (1, 7, 15, 30, 45)


class Sector(str, Enum):
    RURAL = "Rural"
    URBAN = "Urban"
    COMBINED = "Combined"


class Provenance(str, Enum):
    """How a fare observation came to exist. Never inferred, always recorded.

    LIVE_SCRAPE      -- Playwright read it off a robots-allowed public page.
    OFFICIAL_API     -- Amadeus Self-Service / Duffel returned it under their ToS.
    RECONSTRUCTED    -- generated by the anchored model in apix.pipeline.reconstruct,
                        calibrated on published CPI/DGCA/ATF anchors. NOT a real quote.
    """

    LIVE_SCRAPE = "LIVE_SCRAPE"
    OFFICIAL_API = "OFFICIAL_API"
    RECONSTRUCTED = "RECONSTRUCTED"

    @property
    def is_observed(self) -> bool:
        return self in (Provenance.LIVE_SCRAPE, Provenance.OFFICIAL_API)


