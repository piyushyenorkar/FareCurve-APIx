@dataclass(frozen=True)
class Route:
    origin: str
    destination: str
    tier: int  # 1 = PS-named core basket, 2 = high-traffic extension
    notes: str = ""

    @property
    def key(self) -> str:
        return f"{self.origin}-{self.destination}"

    @property
    def label(self) -> str:
        return f"{AIRPORTS[self.origin].city} → {AIRPORTS[self.destination].city}"

    @property
    def unordered_key(self) -> str:
        """Directionless key, for joining to O&D traffic tables that are symmetric."""
        return "-".join(sorted((self.origin, self.destination)))


