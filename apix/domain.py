def expected_observations_per_day(
    n_routes: int | None = None, n_sources: int | None = None
) -> int:
    """Denominator of the confidence score: routes x windows x enabled sources."""
    n_routes = len(ROUTE_BASKET) if n_routes is None else n_routes
    n_sources = len(SOURCES) if n_sources is None else n_sources
    return n_routes * len(BOOKING_WINDOWS) * n_sources



